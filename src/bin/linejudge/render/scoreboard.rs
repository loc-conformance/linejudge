use maud::{Markup, html};

use crate::render::data::{Answer, Counter, Counts, Region, Sweep, Verdict};
use crate::render::{
    CASES_DIR, DATA_FILE, format_as_one_line, format_the_group_title, wrap_the_page,
};

const OPEN_TIP: &str = "the tool disagrees with its own rules here, and nobody has reviewed the \
                        disagreement yet to say why";
const UNCLAIMED_TIP: &str = "the tool does not support this file's language, so the case counts \
                             neither for nor against it";
const CASES_COLUMN_REM: usize = 25;
const TOOL_COLUMN_REM: usize = 16;

pub fn render_the_scoreboard(sweep: &Sweep) -> String {
    let counted: usize = sweep
        .groups
        .iter()
        .map(|group| group.cases.iter().filter(|case| !case.disabled).count())
        .sum();
    // The width of the cases column is written here and in `page.css`: the stylesheet sizes the
    // column and this is what the table is told it needs at its narrowest.
    let width = CASES_COLUMN_REM + TOOL_COLUMN_REM * sweep.counters.len();
    let body = html! {
        (render_the_header(sweep, counted))
        table style=(format!("min-width: {width}rem")) {
            colgroup {
                col .cases;
                @for _ in &sweep.counters { col; }
            }
            thead { tr {
                th {}
                @for counter in &sweep.counters { (render_one_column_head(counter)) }
            } }
            tbody {
                @for group in &sweep.groups {
                    tr .group { td colspan=(sweep.counters.len() + 1) {
                        span { (format_the_group_title(&group.name)) }
                    } }
                    @for case in &group.cases {
                        @if case.disabled {
                            tr .disabled {
                                td .case { span .tag { "disabled" } (case.name) }
                                @for _ in &sweep.counters { td {} }
                            }
                        } @else {
                            tr {
                                td .case {
                                    a .tip href=(format!("{CASES_DIR}/{}.html", case.name))
                                            data-tip=(format_as_one_line(&case.trap)) {
                                        (case.name)
                                    }
                                }
                                @for counter in &sweep.counters {
                                    (render_one_cell(counter, &case.name))
                                }
                            }
                        }
                    }
                }
            }
        }
        footer { "measured on " (sweep.measured_on) " · generated by linejudge" }
    };
    wrap_the_page("line counting conformance", body, "")
}

fn render_the_header(sweep: &Sweep, counted: usize) -> Markup {
    html! {
        header {
            h1 { "Line counting conformance" }
            p .intro {
                "Every tool below is judged against its own declared rules, so a failure means \
                 the tool disagrees with itself. Hover elements like the test name or the status \
                 result for more information or the reasons."
            }
            p .meta {
                "measured " (sweep.measured_on)
                " · corpus of " (counted) " cases in " (sweep.groups.len()) " groups · "
                a href=(DATA_FILE) { (DATA_FILE) }
            }
            div .legend {
                span { span .s.s-pass { "✓" } " agrees" }
                span { span .s.s-pass { "✓" } span .idot { "ⓘ" } " agrees, with a note" }
                span { span .s.s-exc { "◆" } " agrees through a declared exception" }
                span { span .s.s-fail { "✗" } " fails, reviewed" }
                span { span .s.s-open { "✗" } " fails, not yet reviewed" }
                span { span .s.s-na { "⊘" } " does not support this language" }
                span { span .s.s-broke { "broke" } }
            }
        }
    }
}

fn render_one_column_head(counter: &Counter) -> Markup {
    let multi = counter.dialects.len() > 1;
    html! {
        th {
            div .tname { (counter.name) }
            div .tver title=(counter.version) { (format_the_version_of(counter)) }
            div .chips {
                @for (at, dialect) in counter.dialects.iter().enumerate() {
                    span .chip .pick[multi] .active[multi && at == 0]
                            data-group=[multi.then_some(&counter.name)]
                            data-value=[multi.then_some(&dialect.name)] {
                        (dialect.name) " · " (render_one_tally(&dialect.answers))
                    }
                }
            }
        }
    }
}

fn render_one_tally(answers: &[Answer]) -> Markup {
    let of = |wanted: &dyn Fn(&Answer) -> bool| answers.iter().filter(|a| wanted(a)).count();
    let agrees = of(&|a| a.verdict == Verdict::Agrees);
    let fails = of(&|a| a.verdict == Verdict::Fails && a.note.is_some());
    let open = of(&|a| a.verdict == Verdict::Fails && a.note.is_none());
    let unclaimed = of(&|a| a.verdict == Verdict::Unclaimed);
    let broke = of(&|a| a.verdict == Verdict::Broke);
    html! {
        b .ok { (agrees) "✓" }
        @if fails > 0 { " " b .bad { (fails) "✗" } }
        @if open > 0 { " " b .open { (open) " open" } }
        @if unclaimed > 0 { " " b .na { (unclaimed) "⊘" } }
        @if broke > 0 { " " b .bad { (broke) " broke" } }
    }
}

fn render_one_cell(counter: &Counter, case: &str) -> Markup {
    let multi = counter.dialects.len() > 1;
    html! {
        td {
            @for (at, dialect) in counter.dialects.iter().enumerate() {
                @let answer = dialect.answers.iter().find(|answer| answer.case == case);
                @if multi {
                    div .dv data-group=(counter.name) data-value=(dialect.name) hidden[at > 0] {
                        @if let Some(answer) = answer { (render_one_answer(answer)) }
                    }
                } @else {
                    @if let Some(answer) = answer { (render_one_answer(answer)) }
                }
            }
        }
    }
}

fn render_one_answer(answer: &Answer) -> Markup {
    match answer.verdict {
        Verdict::Broke => {
            let message = answer.broke.as_deref().unwrap_or("broke");
            html! { span .status.s-broke.tip data-tip=(format_as_one_line(message)) { "broke" } }
        }
        Verdict::Unclaimed => html! {
            span .status.s-na.tip data-tip=(UNCLAIMED_TIP) { "⊘ not claimed" }
        },
        Verdict::Agrees => match (&answer.exception, &answer.note) {
            (Some(exception), _) => html! {
                span .status.s-exc.tip
                        data-tip=(format!("declared intent: {}", format_as_one_line(exception))) {
                    "◆ agrees · exception"
                }
            },
            (None, Some(note)) => html! {
                span .status.s-pass.tip data-tip=(format_as_one_line(note)) {
                    "✓ " span .idot { "ⓘ" }
                }
            },
            (None, None) => html! { span .status.s-pass { "✓" } },
        },
        Verdict::Fails => render_one_failure(answer),
    }
}

fn render_one_failure(answer: &Answer) -> Markup {
    let differing = match (&answer.wants, &answer.answered) {
        (Some(wants), Some(answered)) => find_the_differing_counts(wants, answered),
        _ => Vec::new(),
    };
    let regions_moved = answer.wants_regions != answer.answered_regions;
    let label = match differing.is_empty() && regions_moved {
        true => "✗ regions differ",
        false => "✗ fails",
    };
    html! {
        @match &answer.note {
            Some(note) => span .status.s-fail.tip data-tip=(format_as_one_line(note)) { (label) },
            None => span .status.s-open.tip data-tip=(OPEN_TIP) { (label) " · unreviewed" },
        }
        div .nums {
            @if !differing.is_empty() {
                span .lbl { "wants" }
                (format_one_row(&differing, false))
                br;
                span .lbl { "answers" }
                (format_one_row(&differing, true))
                @if regions_moved { br; }
            }
            @if regions_moved {
                (render_the_region_rows(&answer.wants_regions, &answer.answered_regions))
            }
        }
    }
}

/// The lines and every bucket whose two sides disagree, as (name, wanted, answered), so a cell
/// shows only what moved.
fn find_the_differing_counts(wants: &Counts, answered: &Counts) -> Vec<(String, u32, u32)> {
    let mut differing = Vec::new();
    if wants.lines != answered.lines {
        differing.push(("lines".to_string(), wants.lines, answered.lines));
    }
    for (name, wanted) in &wants.buckets {
        let got = answered.buckets.get(name).copied().unwrap_or(0);
        if *wanted != got {
            differing.push((name.clone(), *wanted, got));
        }
    }
    differing
}

fn format_one_row(differing: &[(String, u32, u32)], answered_side: bool) -> Markup {
    html! {
        @for (at, (name, wanted, got)) in differing.iter().enumerate() {
            @if at > 0 { " · " }
            @if answered_side { span .off { (got) " " (name) } }
            @else { (wanted) " " (name) }
        }
    }
}

/// Regions can differ without their headline moving: the same language over the same lines with
/// the lines binned differently inside it. So a whole side missing is said in one line, and
/// otherwise each language whose two sides disagree gets a row naming exactly what moved.
fn render_the_region_rows(wants: &[Region], answered: &[Region]) -> Markup {
    if wants.is_empty() || answered.is_empty() {
        return html! {
            span .lbl { "regions" }
            @if answered.is_empty() {
                "wants " (format_the_regions_of(wants)) " · finds " span .off { "none" }
            } @else {
                "wants none · finds " span .off { (format_the_regions_of(answered)) }
            }
        };
    }
    let mut languages: Vec<&str> =
        wants.iter().chain(answered).map(|region| region.language.as_str()).collect();
    languages.sort_unstable();
    languages.dedup();
    let differing: Vec<&str> = languages
        .into_iter()
        .filter(|language| {
            find_the_region_of(wants, language) != find_the_region_of(answered, language)
        })
        .collect();
    html! {
        @for (at, language) in differing.iter().enumerate() {
            @if at > 0 { br; }
            span .lbl { @if at == 0 { "regions" } }
            (language) " · "
            @match (find_the_region_of(wants, language), find_the_region_of(answered, language)) {
                (Some(wanted), Some(found)) => {
                    @let moved = find_the_differing_counts(&wanted.to_counts(), &found.to_counts());
                    "wants " (format_one_row(&moved, false))
                    " · answers " (format_one_row(&moved, true))
                }
                (Some(wanted), None) => {
                    (format_the_lines_of(wanted.lines)) " · finds " span .off { "none" }
                }
                (None, Some(found)) => {
                    "wanted none · finds " span .off { (format_the_lines_of(found.lines)) }
                }
                (None, None) => {}
            }
        }
    }
}

fn find_the_region_of<'a>(regions: &'a [Region], language: &str) -> Option<&'a Region> {
    regions.iter().find(|region| region.language == language)
}

fn format_the_lines_of(lines: u32) -> String {
    match lines {
        1 => "1 line".to_string(),
        _ => format!("{lines} lines"),
    }
}

fn format_the_regions_of(regions: &[Region]) -> String {
    regions
        .iter()
        .map(|region| format!("{} {}", region.language, region.lines))
        .collect::<Vec<_>>()
        .join(" · ")
}

/// The version as the column head shows it: most tools open their version line by repeating
/// their own name, which the head has just said in bold.
fn format_the_version_of(counter: &Counter) -> &str {
    counter
        .version
        .strip_prefix(&counter.name)
        .map(str::trim_start)
        .filter(|rest| !rest.is_empty())
        .unwrap_or(&counter.version)
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;
    use std::env;
    use std::fs;
    use std::path::PathBuf;

    use super::*;

    #[test]
    fn the_scoreboard_matches_its_golden_file() {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/render");
        let read = |name: &str| {
            fs::read_to_string(dir.join(name))
                .unwrap_or_else(|error| panic!("{name}: {error}"))
                .replace("\r\n", "\n")
        };
        let sweep: Sweep = serde_json::from_str(&read("record.json"))
            .unwrap_or_else(|error| panic!("record.json: {error}"));
        let rendered = render_the_scoreboard(&sweep);
        if env::var("LINEJUDGE_UPDATE_GOLDEN").is_ok() {
            fs::write(dir.join("index.golden.html"), &rendered)
                .unwrap_or_else(|error| panic!("index.golden.html: {error}"));
        }
        assert_eq!(rendered, read("index.golden.html"));
    }

    #[test]
    fn a_failure_shows_the_lines_and_the_buckets_that_moved_and_nothing_else() {
        let differing = find_the_differing_counts(
            &counts(4, &[("code", 1), ("comments", 3)]),
            &counts(4, &[("code", 3), ("comments", 1)]),
        );
        let named: Vec<&str> = differing.iter().map(|(name, _, _)| name.as_str()).collect();
        assert_eq!(named, ["code", "comments"]);

        let with_lines = find_the_differing_counts(
            &counts(4, &[("code", 4)]),
            &counts(5, &[("code", 4)]),
        );
        assert_eq!(with_lines, [("lines".to_string(), 4, 5)]);
    }

    #[test]
    fn a_failure_whose_totals_agree_is_named_by_its_regions() {
        let mut answer = Answer {
            case: "0400-a_case".to_string(),
            verdict: Verdict::Fails,
            wants: Some(counts(4, &[("code", 4)])),
            answered: Some(counts(4, &[("code", 4)])),
            wants_regions: vec![Region {
                language: "CSS".to_string(),
                lines: 2,
                buckets: BTreeMap::new(),
            }],
            answered_regions: Vec::new(),
            note: None,
            exception: None,
            broke: None,
            command: String::new(),
        };
        let shown = render_one_answer(&answer).into_string();
        assert!(shown.contains("regions differ"), "{shown}");
        assert!(shown.contains("unreviewed"), "{shown}");
        assert!(shown.contains("CSS 2"), "{shown}");

        answer.answered = Some(counts(4, &[("code", 3)]));
        let shown = render_one_answer(&answer).into_string();
        assert!(shown.contains("✗ fails"), "{shown}");
        assert!(!shown.contains("regions differ"), "{shown}");
    }

    #[test]
    fn a_region_that_differs_only_inside_itself_shows_what_moved_per_language() {
        let region = |language: &str, lines: u32, code: u32, comments: u32| Region {
            language: language.to_string(),
            lines,
            buckets: BTreeMap::from([
                ("code".to_string(), code),
                ("comments".to_string(), comments),
            ]),
        };
        let rows = render_the_region_rows(
            &[region("HTML", 2, 2, 0), region("Markdown", 2, 1, 1)],
            &[region("Markdown", 2, 0, 2)],
        )
        .into_string();
        assert!(rows.contains("Markdown · wants 1 code · 1 comments"), "{rows}");
        assert!(rows.contains("0 code"), "{rows}");
        assert!(rows.contains("HTML · 2 lines · finds"), "{rows}");
        assert!(!rows.contains("Markdown 2"), "the headline says nothing, so it is not shown");

        let unwanted = render_the_region_rows(
            &[region("Markdown", 2, 1, 1)],
            &[region("Markdown", 2, 1, 1), region("HTML", 1, 1, 0)],
        )
        .into_string();
        assert!(unwanted.contains("HTML · wanted none · finds"), "{unwanted}");
        assert!(unwanted.contains("1 line"), "{unwanted}");
        assert!(!unwanted.contains("Markdown"), "an agreeing region earns no row\n{unwanted}");
    }

    #[test]
    fn each_state_speaks_for_itself_when_hovered() {
        let mut answer = Answer {
            case: "0400-a_case".to_string(),
            verdict: Verdict::Unclaimed,
            wants: Some(counts(4, &[("code", 4)])),
            answered: None,
            wants_regions: Vec::new(),
            answered_regions: Vec::new(),
            note: None,
            exception: None,
            broke: None,
            command: String::new(),
        };
        assert!(render_one_answer(&answer).into_string().contains(UNCLAIMED_TIP));

        answer.verdict = Verdict::Broke;
        answer.broke = Some("exit status 101".to_string());
        assert!(render_one_answer(&answer).into_string().contains("exit status 101"));

        answer.verdict = Verdict::Agrees;
        answer.broke = None;
        answer.exception = Some("counts the shebang as comment".to_string());
        let shown = render_one_answer(&answer).into_string();
        assert!(shown.contains("declared intent: counts the shebang as comment"), "{shown}");
    }

    fn counts(lines: u32, buckets: &[(&str, u32)]) -> Counts {
        Counts {
            lines,
            buckets: buckets.iter().map(|(name, value)| (name.to_string(), *value)).collect(),
        }
    }
}
